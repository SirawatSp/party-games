self.addEventListener("install", (event) => {
  event.waitUntil(
    caches
      .open(CACHE_VERSION)
      .then((cache) => cache.addAll(PRECACHE_URLS))
      .then(() => self.skipWaiting())
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE_VERSION).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener("fetch", (event) => {
  const req = event.request;
  if (req.method !== "GET") return;
  // ข้ามคำขอข้ามโดเมน (เช่นฟอนต์จาก Google Fonts) ให้เบราว์เซอร์จัดการตามปกติ
  // ตอนออฟไลน์ฟอนต์จะโหลดไม่ได้ก็แค่ fallback ไปฟอนต์ระบบ ไม่กระทบการเล่น
  if (new URL(req.url).origin !== self.location.origin) return;

  // หน้าเกมที่ระบุรุ่นไฟล์ต้องโหลดชุดล่าสุด ป้องกันหน้าใหม่ใช้คลังหรือสคริปต์เก่าจาก cache
  // ไฟล์เกมระบุรุ่นใน URL แล้ว จึงยังเปิดออฟไลน์ได้ด้วยชุดไฟล์รุ่นเดียวกัน
  const freshGame = ["doodle-race.html", "witness-sketch.html", "situation.html", "flashquiz.html"].find(page => new URL(req.url).pathname.endsWith("/" + page));
  if (req.mode === "navigate" && freshGame) {
    event.respondWith(fetch(req, { cache: "no-store" }).then((res) => {
      if (res.status === 200) {
        const clone = res.clone();
        return caches.open(CACHE_VERSION).then((cache) => cache.put(req, clone)).catch(() => {}).then(() => res);
      }
      return caches.match(req).then((cached) => cached || res);
    }).catch(() => caches.match(req).then((cached) => cached || caches.match(freshGame))));
    return;
  }

  event.respondWith(
    caches.match(req).then((cached) => {
      const network = fetch(req)
        .then((res) => {
          if (res && res.status === 200) {
            const clone = res.clone();
            caches.open(CACHE_VERSION).then((cache) => cache.put(req, clone));
          }
          return res;
        })
        .catch(() => cached);
      // cache-first: มีของเก่าให้ใช้ก่อนเลยเพื่อความเร็ว/ออฟไลน์ พร้อมอัปเดตของใหม่เงียบ ๆ เบื้องหลัง
      return cached || network;
    })
  );
});
